<?php

declare(strict_types=1);

namespace LTS\PHPQA\Tests\Small\Pipeline\Lane\ComposerChecks;

use Iterator;
use LTS\PHPQA\Pipeline\Lane\ComposerChecks\NestedManifestSelector;
use LTS\PHPQA\Tests\Support\ContextFactory;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\Small;
use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\Attributes\UsesClass;
use PHPUnit\Framework\TestCase;

/**
 * Which composer.json files below the project root are Composer projects of their own: every one
 * the project's files hold, bar those under a path the project ignores or declares unanalysed,
 * and the default exclusions (`vendor/`, `var/`).
 *
 * @internal
 */
#[CoversClass(NestedManifestSelector::class)]
#[UsesClass(\LTS\PHPQA\Pipeline\Config\Dto\DeadCodeOptionsDto::class)]
#[UsesClass(\LTS\PHPQA\Pipeline\Config\Dto\InfectionOptionsDto::class)]
#[UsesClass(\LTS\PHPQA\Pipeline\Config\Dto\PhpUnitOptionsDto::class)]
#[UsesClass(\LTS\PHPQA\Pipeline\Config\Dto\ProjectPathsDto::class)]
#[UsesClass(\LTS\PHPQA\Pipeline\Config\Dto\QaConfigDto::class)]
#[UsesClass(\LTS\PHPQA\Pipeline\Config\Dto\TypeCoverageOptionsDto::class)]
#[UsesClass(\LTS\PHPQA\Pipeline\Config\EnvironmentReader::class)]
#[UsesClass(\LTS\PHPQA\Pipeline\Config\IgnoredPaths::class)]
#[UsesClass(\LTS\PHPQA\Pipeline\Config\QaConfigBuilder::class)]
#[UsesClass(\LTS\PHPQA\Changelog\ReleaseVersionPolicy::class)]
#[Small]
final class NestedManifestSelectorTest extends TestCase
{
    private const string ROOT_MANIFEST = 'composer.json';

    private const string TOOL_MANIFEST = 'tools/a/composer.json';

    private const string SECOND_MANIFEST = 'tools/b/composer.json';

    private const string FIXTURE_MANIFEST = 'tests/assets/p/composer.json';

    private const string REASON = 'generated by a build step';

    private ContextFactory $factory;

    protected function setUp(): void
    {
        $this->factory = ContextFactory::create();
    }

    protected function tearDown(): void
    {
        $this->factory->project->remove();
    }

    #[Test]
    public function aNestedManifestIsSelectedAndTheRootOneIsNot(): void
    {
        $selected = new NestedManifestSelector()->select($this->factory->builder()->build(), self::ROOT_MANIFEST, self::TOOL_MANIFEST, 'src/Foo.php');

        self::assertSame([self::TOOL_MANIFEST], $selected);
    }

    #[Test]
    public function theSelectionIsSortedAndListsEachManifestOnce(): void
    {
        $selected = new NestedManifestSelector()->select($this->factory->builder()->build(), self::SECOND_MANIFEST, self::TOOL_MANIFEST, self::SECOND_MANIFEST);

        self::assertSame([self::TOOL_MANIFEST, self::SECOND_MANIFEST], $selected);
    }

    /** @param list<string> $files */
    #[Test]
    #[DataProvider('notManifests')]
    public function aFileThatIsNotNamedComposerJsonIsNotAManifest(array $files): void
    {
        self::assertSame([], new NestedManifestSelector()->select($this->factory->builder()->build(), ...$files));
    }

    /** @return Iterator<string, array{list<string>}> */
    public static function notManifests(): Iterator
    {
        yield 'a lock file' => [['tools/a/composer.lock']];

        yield 'a dist copy' => [['tools/a/composer.json.dist']];

        yield 'a name that ends in the file name' => [['tools/a/mycomposer.json']];

        yield 'a directory of that name holding something else' => [['tools/composer.json/readme.md']];
    }

    /** @param list<string> $files */
    #[Test]
    #[DataProvider('defaultExclusions')]
    public function aManifestUnderADefaultExclusionIsNotSelected(array $files): void
    {
        self::assertSame([], new NestedManifestSelector()->select($this->factory->builder()->build(), ...$files));
    }

    /** @return Iterator<string, array{list<string>}> */
    public static function defaultExclusions(): Iterator
    {
        yield 'vendor' => [['vendor/acme/lib/composer.json']];

        yield 'var' => [['var/qa/cache/composer.json']];
    }

    #[Test]
    public function aManifestUnderAnIgnoredPathIsNotSelected(): void
    {
        $config = $this->factory->builder()->withIgnoredPaths('tests/assets')->build();

        self::assertSame([self::TOOL_MANIFEST], new NestedManifestSelector()->select($config, self::FIXTURE_MANIFEST, self::TOOL_MANIFEST));
    }

    #[Test]
    public function anIgnoredPathIsReadHoweverItIsSpelt(): void
    {
        $config = $this->factory->builder()->withIgnoredPaths('./tests/assets/')->build();

        self::assertSame([], new NestedManifestSelector()->select($config, self::FIXTURE_MANIFEST));
    }

    #[Test]
    public function anIgnoredPathDoesNotSwallowASiblingThatSharesItsPrefix(): void
    {
        $config = $this->factory->builder()->withIgnoredPaths('tests/assets')->build();

        self::assertSame(['tests/assetsExtra/composer.json'], new NestedManifestSelector()->select($config, 'tests/assetsExtra/composer.json'));
    }

    #[Test]
    public function aManifestUnderAPathDeclaredUnanalysedIsNotSelected(): void
    {
        $config = $this->factory->builder()->withUnanalysedPath('tools/a', self::REASON)->build();

        self::assertSame([self::SECOND_MANIFEST], new NestedManifestSelector()->select($config, self::TOOL_MANIFEST, self::SECOND_MANIFEST));
    }

    /** A path made of digits is an int array key in the declarations; it is still a path. */
    #[Test]
    public function aDeclaredPathNamedInDigitsIsRead(): void
    {
        $config = $this->factory->builder()->withUnanalysedPath('2024', self::REASON)->build();

        self::assertSame([], new NestedManifestSelector()->select($config, '2024/composer.json'));
    }

    #[Test]
    public function aManifestNestedInsideADefaultNamedDirectoryBelowTheRootIsStillSelected(): void
    {
        self::assertSame(['docs/vendor/composer.json'], new NestedManifestSelector()->select($this->factory->builder()->build(), 'docs/vendor/composer.json'));
    }
}
