<?php

declare(strict_types=1);

namespace LTS\PHPQA\Pipeline\Lane\TwigCsFixer;

/**
 * The source of a twig-cs-fixer config that is the project's resolved .twig-cs-fixer.php
 * with its cache file moved under var/qa/cache.
 *
 * twig-cs-fixer takes no cache path on its command line, only `--no-cache`, and otherwise
 * caches in `.twig-cs-fixer.cache` in its working directory, the project root. The cache
 * file is a config setting, so the lane wraps whatever config resolves, as the phpCsFixer
 * lane's FilteredFinderConfig does, rather than relying on the shipped default, which a
 * project copy in qaConfig/ replaces. A cache manager wins over the cache file, so one the
 * project set is dropped. The project's config is required inside a closure so its
 * variables cannot collide with the wrapper's.
 *
 * @internal
 */
final readonly class CacheFileConfig
{
    public function source(string $projectConfig, string $cacheFile): string
    {
        return \sprintf(
            <<<'PHP_WRAP'
                <?php

                declare(strict_types=1);

                // Generated by php-qa-ci's twigCsFixer lane on every run; edits are overwritten.
                // The project's resolved twig-cs-fixer config, with its cache under var/qa/cache.

                $config = (static fn (): mixed => require %s)();
                $config->setCacheManager(null);
                $config->setCacheFile(%s);

                return $config;

                PHP_WRAP,
            var_export($projectConfig, true),
            var_export($cacheFile, true),
        );
    }
}
