<?php

declare(strict_types=1);

namespace LTS\PHPQA\Pipeline\Lane\PhpCsFixer;

use LTS\PHPQA\Pipeline\Config\IgnoredPaths;

/**
 * The source of a PHP CS Fixer config that is the project's resolved
 * php_cs.php with its finder filtered: the ignored paths are taken out, and
 * so is every file whose real path cannot be resolved (a dangling symlink),
 * which is named in a list file for the lane to report. Such a file is
 * named, and matched against the ignored paths, by its directory's real path.
 *
 * The lane runs the fixer with `--path-mode=intersection`, in which the paths
 * on the command line only narrow what the config's finder yields (verified in
 * the shipped phar's ConfigurationResolver::resolveFinder()), so an exclusion
 * has to be in the finder to survive. Putting it in the shipped php_cs.php or
 * php_cs_finder.php would lose it for every project that has copied either
 * into qaConfig/; wrapping whatever config resolves keeps it for all of them,
 * as the PHPStan lane's wrapper neon does. The same narrowing calls
 * `str_starts_with($file->getRealPath(), ...)` on every file the finder
 * yields, and a false real path kills the fixer with a TypeError (#239), so
 * such a file must never reach it.
 *
 * The project's config is required inside a closure so its variables cannot
 * collide with the wrapper's. The finder is wrapped rather than given a
 * notPath(): a project finder may be any iterable, rooted anywhere, and a real
 * path comparison is right for all of them. Each iteration starts afresh, so
 * the finder can be read more than once; a file it skips is appended to the
 * list each time, and the lane reports each name once.
 *
 * @internal
 */
final readonly class FilteredFinderConfig
{
    public function source(string $projectConfig, IgnoredPaths $ignored, string $unresolvedList): string
    {
        $real = array_map(static fn (string $path): string => file_exists($path) ? \Safe\realpath($path) : $path, $ignored->absolute);

        return \sprintf(
            <<<'PHP_WRAP'
                <?php

                declare(strict_types=1);

                // Generated by php-qa-ci's phpCsFixer lane on every run; edits are overwritten.
                // The project's resolved PHP CS Fixer config, less its withIgnoredPaths() and
                // any file whose real path cannot be resolved, which is listed for the lane.

                $config = (static fn (): mixed => require %s)();

                $config->setFinder(new class ($config->getFinder(), %s, %s) implements IteratorAggregate {
                    public function __construct(private readonly iterable $finder, private readonly array $ignored, private readonly string $unresolved)
                    {
                    }

                    public function getIterator(): Generator
                    {
                        foreach ($this->finder as $key => $file) {
                            $path     = $file->getRealPath();
                            $resolved = false !== $path;
                            if (!$resolved) {
                                $dir  = realpath($file->getPath());
                                $path = false === $dir ? $file->getPathname() : $dir . '/' . $file->getFilename();
                            }

                            foreach ($this->ignored as $ignored) {
                                if ($path === $ignored || str_starts_with($path, $ignored . '/')) {
                                    continue 2;
                                }
                            }

                            if (!$resolved) {
                                file_put_contents($this->unresolved, $path . "\n", FILE_APPEND | LOCK_EX);

                                continue;
                            }

                            yield $key => $file;
                        }
                    }
                });

                return $config;

                PHP_WRAP,
            var_export($projectConfig, true),
            var_export($real, true),
            var_export($unresolvedList, true),
        );
    }
}
