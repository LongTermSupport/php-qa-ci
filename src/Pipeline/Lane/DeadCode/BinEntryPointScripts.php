<?php

declare(strict_types=1);

namespace LTS\PHPQA\Pipeline\Lane\DeadCode;

use LTS\PHPQA\Pipeline\Config\IgnoredPaths;
use LTS\PHPQA\Pipeline\Lane\DeadCode\Dto\BinScanDto;
use Safe\Exceptions\DirException;
use Safe\Exceptions\FilesystemException;

/**
 * The PHP scripts under a project's bin/ that nothing the lane's run analyses.
 *
 * What the run analyses is what PHPStan makes of the lane's paths (src/, tests/ and the declared
 * entry points) merged with the project's own phpstan.neon `paths`, `excludePaths` and
 * `fileExtensions` (AnalysedFiles). A bin/ script with no `.php` suffix is read only when it is
 * listed there; one left off is analysed by nothing, and every member only it reaches is reported
 * dead. Every file under bin/ is read, at any depth and through links, and judged by the file it
 * resolves to.
 *
 * A file is PHP by its content, after an optional UTF-8 BOM: a `#!` line whose command is a PHP
 * binary (php, php-cgi or phpdbg, versioned or not, directly or through env past its options
 * and NAME=value assignments), or, with no `#!` line, a `<?php` open tag in any case or a `<?=`
 * tag after nothing but blank space. A `#!` line naming any other command makes it not PHP.
 *
 * A PHP file is required unless the run already analyses it. Not required, each with the reason:
 *
 * - a script in another language, which PHPStan does not read;
 * - a Composer binary proxy, recognised by the template Composer's BinaryInstaller writes (its
 *   header docblock first, `namespace Composer;`, and `return include` last), whatever it
 *   includes: it holds no code of its own, and Composer rewrites it on every install;
 * - a file that resolves into Composer's vendor dir (wherever it is, bin/ included) or out of
 *   the project: the project cannot change code it does not own, so a finding in it could not
 *   be fixed;
 * - a file under a withIgnoredPaths() entry, by its bin/ path or its target's: the project has
 *   recorded that the tree is not analysed, and every lane honours that;
 * - a file git ignores, by its bin/ path or its target's (GitIgnoredFiles): it is never
 *   committed, so CI never has it, and requiring it would make the verdict depend on one
 *   checkout's local state (Symfony's simple-phpunit installs PHPUnit under bin/.phpunit);
 * - a dangling link, which holds no script to analyse.
 *
 * A linked directory whose real path is out of the project or in the vendor dir is not walked, so
 * a link to `/` reads nothing. A path that cannot be read, a directory that cannot be listed or a
 * file whose content or real path cannot be had, is reported as unreadable rather than passed:
 * it may hold an undeclared script.
 *
 * @internal
 */
final readonly class BinEntryPointScripts
{
    /** The directory scanned, relative to the project root, and the prefix of every path reported. */
    private const string BIN = 'bin';

    /** How many bytes of a file decide whether it is PHP: the BOM and the `#!` line or open tag. */
    private const int HEAD_BYTES = 512;

    /** The most of a file read to recognise a Composer proxy; Composer's is under 5 KiB. */
    private const int PROXY_BYTES = 16384;

    /** A UTF-8 byte-order mark, which PHP skips before the open tag. */
    private const string BOM = "\u{FEFF}";

    /** A `#!` line; the group is the command and its arguments. */
    private const string SHEBANG = '~\A#!([^\r\n]*)~';

    /** With no `#!` line: PHP's open tag (case-insensitive, then whitespace) or its echo tag, after blank space only. */
    private const string OPEN_TAG = '~\A[\r\n\t ]*<\?(?:php(?=\s|\z)|=)~i';

    /** A PHP binary that runs a script: php, php-cgi or phpdbg, with an optional version (php8.5, php85). */
    private const string PHP_BINARY = '~\A(?:php|php-cgi|phpdbg)(?:\d+(?:\.\d+)*)?\z~';

    /** The basename of the `#!` command that runs another, found past its options. */
    private const string ENV = 'env';

    /** env options that take the next word as their argument (`-u NAME`, `-C DIR`). */
    private const array ENV_OPTIONS_WITH_ARGUMENT = ['-u', '--unset', '-C', '--chdir', '-P'];

    /**
     * What Composer's BinaryInstaller writes at the start of a PHP proxy: a `#!` line, the open
     * tag, a docblock naming the included path, and Composer's namespace.
     */
    private const string COMPOSER_PROXY = "~\\A#![^\n]*\n<\\?php\n\n/\\*\\*\n \\* Proxy PHP file generated by Composer\n \\*\n \\* This file includes the referenced bin path \\([^\n]+\\)\n(?: \\*[^\n]*\n)* \\*/\n\nnamespace Composer;\n~";

    /** And at its end: the include of that path, and nothing after it. */
    private const string COMPOSER_PROXY_END = "~\nreturn include [^\n]+;\n?\\z~";

    /** Read for its `config.vendor-dir`. */
    private const string COMPOSER_JSON = 'composer.json';

    /** Composer's vendor dir when composer.json does not configure one. */
    private const string DEFAULT_VENDOR_DIR = 'vendor';

    /** Joins path segments. */
    private const string SEPARATOR = '/';

    public function __construct(private IgnoredPaths $ignored, private AnalysedFiles $analysed, private GitIgnoredFiles $gitIgnored)
    {
    }

    /** @param string $projectRoot absolute */
    public function scan(string $projectRoot): BinScanDto
    {
        $binDir = $projectRoot . self::SEPARATOR . self::BIN;
        if (!is_dir($binDir)) {
            return new BinScanDto([], []);
        }

        $root       = \Safe\realpath($projectRoot);
        $vendorDir  = $this->vendorDir($root);
        $visited    = [];
        $unreadable = [];
        $undeclared = [];
        foreach ($this->filesUnder($binDir, self::BIN, $root, $projectRoot, $vendorDir, $visited, $unreadable) as $key => $path) {
            $relative = (string)$key;
            $real     = $this->realpath($path, $relative, $unreadable);
            if (null === $real) {
                continue;
            }

            if (!$this->isOwned($real, $root, $vendorDir)
                || $this->ignored->contains($this->asConfigured($real, $root, $projectRoot))
                || $this->gitIgnored->contains($this->relativeTo($real, $root))
                || $this->analysed->analyses($real)) {
                continue;
            }

            try {
                if ($this->isFirstPartyPhp($path)) {
                    $undeclared[] = $relative;
                }
            } catch (FilesystemException $unreadableFile) {
                $unreadable[] = $relative . ' (' . $unreadableFile->getMessage() . ')';
            }
        }

        sort($undeclared);
        sort($unreadable);

        return new BinScanDto($undeclared, $unreadable);
    }

    /**
     * Every file under $directory, through links, each directory read once by its real path.
     * A directory out of the project, in Composer's vendor dir, ignored or git-ignored is not
     * entered; a dangling link is no file; what cannot be read goes to $unreadable.
     *
     * @param array<array-key, true> $visited    real paths of the directories already read
     * @param list<string>           $unreadable project-relative
     *
     * @return array<array-key, string> project-relative path => absolute path
     */
    private function filesUnder(string $directory, string $relative, string $root, string $projectRoot, ?string $vendorDir, array &$visited, array &$unreadable): array
    {
        $real = $this->realpath($directory, $relative, $unreadable);
        if (null === $real) {
            return [];
        }

        if (isset($visited[$real])
            || ($real !== $root && !$this->isOwned($real, $root, $vendorDir))
            || $this->ignored->contains($directory) || $this->ignored->contains($this->asConfigured($real, $root, $projectRoot))
            || $this->gitIgnored->contains($relative) || $this->gitIgnored->contains($this->relativeTo($real, $root))) {
            return [];
        }

        $visited[$real] = true;

        try {
            $entries = \Safe\scandir($directory);
        } catch (DirException $dirException) {
            $unreadable[] = $relative . ' (' . $dirException->getMessage() . ')';

            return [];
        }

        $files = [];
        foreach ($entries as $entry) {
            if (!\is_string($entry) || '.' === $entry || '..' === $entry) {
                continue;
            }

            $path = $directory . self::SEPARATOR . $entry;
            $name = $relative . self::SEPARATOR . $entry;
            if (is_dir($path)) {
                $files += $this->filesUnder($path, $name, $root, $projectRoot, $vendorDir, $visited, $unreadable);
            } elseif (is_file($path)) {
                if (!$this->ignored->contains($path) && !$this->gitIgnored->contains($name)) {
                    $files[$name] = $path;
                }
            } elseif (!is_link($path) && !file_exists($path)) {
                // Listed, yet neither it nor a link by its name can be looked at.
                $unreadable[] = $name;
            }
        }

        return $files;
    }

    /**
     * The real path; null, with $relative and the reason added to $unreadable, when it cannot be
     * resolved.
     *
     * @param list<string> $unreadable
     */
    private function realpath(string $path, string $relative, array &$unreadable): ?string
    {
        try {
            return \Safe\realpath($path);
        } catch (FilesystemException $filesystemException) {
            $unreadable[] = $relative . ' (' . $filesystemException->getMessage() . ')';

            return null;
        }
    }

    /** Inside the project and outside Composer's vendor dir. */
    private function isOwned(string $real, string $root, ?string $vendorDir): bool
    {
        return $this->isInside($real, $root) && (null === $vendorDir || ($real !== $vendorDir && !$this->isInside($real, $vendorDir)));
    }

    /** A real path inside the project, spelled from the project root as configured, which is how IgnoredPaths holds it. */
    private function asConfigured(string $real, string $root, string $projectRoot): string
    {
        return $this->isInside($real, $root) ? rtrim($projectRoot, self::SEPARATOR) . substr($real, \strlen($root)) : $real;
    }

    /** A real path inside the project, relative to its root, which is how git lists it; otherwise unchanged. */
    private function relativeTo(string $real, string $root): string
    {
        return $this->isInside($real, $root) ? substr($real, \strlen($root) + 1) : $real;
    }

    private function isInside(string $path, string $directory): bool
    {
        return str_starts_with($path, rtrim($directory, self::SEPARATOR) . self::SEPARATOR);
    }

    /**
     * Composer's `config.vendor-dir` (default `vendor`), resolved; null when it does not exist,
     * since no file can then be inside it.
     */
    private function vendorDir(string $root): ?string
    {
        $composerJson = $root . self::SEPARATOR . self::COMPOSER_JSON;
        $composer     = is_file($composerJson) ? \Safe\json_decode(\Safe\file_get_contents($composerJson), true) : null;
        $config       = \is_array($composer) ? ($composer['config'] ?? null) : null;
        $configured   = \is_array($config) ? ($config['vendor-dir'] ?? null) : null;
        $vendorDir    = \is_string($configured) && '' !== $configured ? rtrim($configured, self::SEPARATOR) : self::DEFAULT_VENDOR_DIR;
        if (!str_starts_with($vendorDir, self::SEPARATOR)) {
            $vendorDir = $root . self::SEPARATOR . $vendorDir;
        }

        return is_dir($vendorDir) ? \Safe\realpath($vendorDir) : null;
    }

    private function isFirstPartyPhp(string $path): bool
    {
        return $this->isPhp(\Safe\file_get_contents($path, false, null, 0, self::HEAD_BYTES))
            && !$this->isComposerProxy(\Safe\file_get_contents($path, false, null, 0, self::PROXY_BYTES));
    }

    private function isPhp(string $head): bool
    {
        if (str_starts_with($head, self::BOM)) {
            $head = substr($head, \strlen(self::BOM));
        }

        $line = 1 === \Safe\preg_match(self::SHEBANG, $head, $shebang) ? ($shebang[1] ?? null) : null;
        if (!\is_string($line)) {
            return 1 === \Safe\preg_match(self::OPEN_TAG, $head);
        }

        $words   = array_values(array_filter(explode(' ', strtr($line, "\t", ' ')), static fn (string $word): bool => '' !== $word));
        $command = array_shift($words);
        if (\is_string($command) && self::ENV === basename($command)) {
            $command = $this->envCommand(...$words);
        }

        return \is_string($command) && 1 === \Safe\preg_match(self::PHP_BINARY, basename($command));
    }

    /** The command env runs: its first word that is not an option, an option's argument or a NAME=value assignment. */
    private function envCommand(string ...$words): ?string
    {
        $isArgument = false;
        foreach ($words as $word) {
            if ($isArgument) {
                $isArgument = false;
            } elseif (\in_array($word, self::ENV_OPTIONS_WITH_ARGUMENT, true)) {
                $isArgument = true;
            } elseif (!str_starts_with($word, '-') && !str_contains($word, '=')) {
                return $word;
            }
        }

        return null;
    }

    /** Composer's proxy template, start and end. */
    private function isComposerProxy(string $contents): bool
    {
        return 1 === \Safe\preg_match(self::COMPOSER_PROXY, $contents)
            && 1 === \Safe\preg_match(self::COMPOSER_PROXY_END, $contents);
    }
}
