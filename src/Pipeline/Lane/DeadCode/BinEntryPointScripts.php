<?php

declare(strict_types=1);

namespace LTS\PHPQA\Pipeline\Lane\DeadCode;

use LTS\PHPQA\Pipeline\Config\IgnoredPaths;

/**
 * The PHP scripts under a project's bin/ that nothing the lane's run analyses.
 *
 * The lane's PHPStan run reads its analysed directories (src/ and tests/), whose `.php` files
 * it finds by scanning, and the declared entry points. A bin/ script with no `.php` suffix is
 * read only when it is declared with withDeadCodeEntryPoints(); one left off the list is
 * analysed by nothing, and every member only it reaches is reported dead. Every file under
 * bin/ is read, at any depth and through links, and judged by the file it resolves to.
 *
 * A file is PHP by its content, after an optional UTF-8 BOM: a `#!` line whose command is a PHP
 * binary (php, php-cgi or phpdbg, versioned or not, directly or through env past its options
 * and NAME=value assignments), or, with no `#!` line, a `<?php` open tag in any case or a `<?=`
 * tag after nothing but blank space. A `#!` line naming any other command makes it not PHP.
 *
 * A PHP file is required unless the run already reads it: its real path is a declared file, or
 * it is a `.php` file inside an analysed directory or a declared one (PHPStan reads only `.php`
 * files from a directory it scans). Declaring a link by its bin/ path or by its target's path
 * both count. The project's own phpstan.neon `excludePaths` and `fileExtensions` are not read.
 * Not required, each with the reason:
 *
 * - a script in another language, which PHPStan does not read;
 * - a Composer binary proxy, which only includes a package's script: recognised by the shape
 *   Composer's BinaryInstaller writes (its header docblock first, naming the included path, and
 *   `return include` last) and by that path resolving into the vendor dir;
 * - a file that resolves into Composer's vendor dir (wherever it is, bin/ included) or out of
 *   the project: the project cannot change code it does not own, so a finding in it could not
 *   be fixed;
 * - a file under a withIgnoredPaths() entry, by its bin/ path or its target's: the project has
 *   recorded that the tree is not analysed, and every lane honours that;
 * - a dangling link, which holds no script to analyse.
 *
 * @internal
 */
final readonly class BinEntryPointScripts
{
    /** The directory scanned, relative to the project root, and the prefix of every path reported. */
    private const string BIN = 'bin';

    /** How many bytes of a file decide whether it is PHP: the BOM and the `#!` line or open tag. */
    private const int HEAD_BYTES = 512;

    /** The most of a file read to recognise a Composer proxy; Composer's is under 5 KiB. */
    private const int PROXY_BYTES = 16384;

    /** A UTF-8 byte-order mark, which PHP skips before the open tag. */
    private const string BOM = "\u{FEFF}";

    /** A `#!` line; the group is the command and its arguments. */
    private const string SHEBANG = '~\A#!([^\r\n]*)~';

    /** With no `#!` line: PHP's open tag (case-insensitive, then whitespace) or its echo tag, after blank space only. */
    private const string OPEN_TAG = '~\A[\r\n\t ]*<\?(?:php(?=\s|\z)|=)~i';

    /** A PHP binary that runs a script: php, php-cgi or phpdbg, with an optional version (php8.5, php85). */
    private const string PHP_BINARY = '~\A(?:php|php-cgi|phpdbg)(?:\d+(?:\.\d+)*)?\z~';

    /** The basename of the `#!` command that runs another, found past its options. */
    private const string ENV = 'env';

    /** env options that take the next word as their argument (`-u NAME`, `-C DIR`). */
    private const array ENV_OPTIONS_WITH_ARGUMENT = ['-u', '--unset', '-C', '--chdir', '-P'];

    /**
     * What Composer's BinaryInstaller writes at the start of a PHP proxy: a `#!` line, the open
     * tag and a docblock naming the included path, relative to the proxy or absolute.
     */
    private const string COMPOSER_PROXY = "~\\A#![^\n]*\n<\\?php\n\n/\\*\\*\n \\* Proxy PHP file generated by Composer\n \\*\n \\* This file includes the referenced bin path \\(([^\n]+)\\)\n(?: \\*[^\n]*\n)* \\*/\n\nnamespace Composer;\n~";

    /** And at its end: the include of that path, and nothing after it. */
    private const string COMPOSER_PROXY_END = "~\nreturn include [^\n]+;\n?\\z~";

    /** Read for its `config.vendor-dir`. */
    private const string COMPOSER_JSON = 'composer.json';

    /** Composer's vendor dir when composer.json does not configure one. */
    private const string DEFAULT_VENDOR_DIR = 'vendor';

    /** The only files PHPStan reads from a directory it scans (its default `fileExtensions`). */
    private const string PHP_SUFFIX = '.php';

    /** @var list<string> absolute: the directories the lane's run scans, src/ and tests/ */
    private array $analysedDirectories;

    public function __construct(private IgnoredPaths $ignored, string ...$analysedDirectories)
    {
        $this->analysedDirectories = array_values($analysedDirectories);
    }

    /**
     * @param string $projectRoot absolute
     * @param string ...$declared absolute paths of the declared entry points, files or directories
     *
     * @return list<string> project-relative paths (`bin/<path>`), sorted
     */
    public function undeclared(string $projectRoot, string ...$declared): array
    {
        $binDir = $projectRoot . '/' . self::BIN;
        if (!is_dir($binDir)) {
            return [];
        }

        $root          = \Safe\realpath($projectRoot);
        $declaredFiles = [];
        $scannedDirs   = [];
        foreach ($declared as $path) {
            if (is_file($path)) {
                $declaredFiles[\Safe\realpath($path)] = true;
            }
        }

        foreach ([...$this->analysedDirectories, ...$declared] as $path) {
            if (is_dir($path)) {
                $scannedDirs[\Safe\realpath($path)] = true;
            }
        }

        $vendorDir  = $this->vendorDir($root);
        $visited    = [];
        $undeclared = [];
        foreach ($this->filesUnder($binDir, self::BIN, $root, $projectRoot, $vendorDir, $visited) as $relative => $path) {
            $real = \Safe\realpath($path);
            if (!$this->isOwned($real, $root, $vendorDir)
                || $this->ignored->contains($this->asConfigured($real, $root, $projectRoot))
                || isset($declaredFiles[$real])
                || $this->isScanned($real, $scannedDirs)) {
                continue;
            }

            if ($this->isFirstPartyPhp($path, $vendorDir)) {
                $undeclared[] = $relative;
            }
        }

        sort($undeclared);

        return $undeclared;
    }

    /**
     * Every file under $directory, through links, each directory read once by its real path.
     * Composer's vendor dir and ignored trees are not entered; a dangling link is no file.
     *
     * @param array<string, true> $visited real paths of the directories already read
     *
     * @return array<string, string> project-relative path => absolute path
     */
    private function filesUnder(string $directory, string $relative, string $root, string $projectRoot, ?string $vendorDir, array &$visited): array
    {
        $real = \Safe\realpath($directory);
        if (isset($visited[$real]) || $real === $vendorDir
                                   || $this->ignored->contains($directory) || $this->ignored->contains($this->asConfigured($real, $root, $projectRoot))) {
            return [];
        }

        $visited[$real] = true;
        $files          = [];
        foreach (\Safe\scandir($directory) as $entry) {
            if (!\is_string($entry) || '.' === $entry || '..' === $entry) {
                continue;
            }

            $path = $directory . '/' . $entry;
            if (is_dir($path)) {
                $files += $this->filesUnder($path, $relative . '/' . $entry, $root, $projectRoot, $vendorDir, $visited);
            } elseif (is_file($path) && !$this->ignored->contains($path)) {
                $files[$relative . '/' . $entry] = $path;
            }
        }

        return $files;
    }

    /** Inside the project and outside Composer's vendor dir. */
    private function isOwned(string $real, string $root, ?string $vendorDir): bool
    {
        return $this->isInside($real, $root) && (null === $vendorDir || !$this->isInside($real, $vendorDir));
    }

    /**
     * A `.php` file inside a directory the run scans.
     *
     * @param array<string, true> $scannedDirs real paths
     */
    private function isScanned(string $real, array $scannedDirs): bool
    {
        if (!str_ends_with($real, self::PHP_SUFFIX)) {
            return false;
        }

        return array_any(array_keys($scannedDirs), fn (string $directory): bool => $this->isInside($real, $directory));
    }

    /** A real path inside the project, spelled from the project root as configured, which is how IgnoredPaths holds it. */
    private function asConfigured(string $real, string $root, string $projectRoot): string
    {
        return $this->isInside($real, $root) ? rtrim($projectRoot, '/') . substr($real, \strlen($root)) : $real;
    }

    private function isInside(string $path, string $directory): bool
    {
        return str_starts_with($path, rtrim($directory, '/') . '/');
    }

    /**
     * Composer's `config.vendor-dir` (default `vendor`), resolved; null when it does not exist,
     * since no file can then be inside it.
     */
    private function vendorDir(string $root): ?string
    {
        $composerJson = $root . '/' . self::COMPOSER_JSON;
        $composer     = is_file($composerJson) ? \Safe\json_decode(\Safe\file_get_contents($composerJson), true) : null;
        $config       = \is_array($composer) ? ($composer['config'] ?? null) : null;
        $configured   = \is_array($config) ? ($config['vendor-dir'] ?? null) : null;
        $vendorDir    = \is_string($configured) && '' !== $configured ? rtrim($configured, '/') : self::DEFAULT_VENDOR_DIR;
        if (!str_starts_with($vendorDir, '/')) {
            $vendorDir = $root . '/' . $vendorDir;
        }

        return is_dir($vendorDir) ? \Safe\realpath($vendorDir) : null;
    }

    private function isFirstPartyPhp(string $path, ?string $vendorDir): bool
    {
        return $this->isPhp(\Safe\file_get_contents($path, false, null, 0, self::HEAD_BYTES))
            && !$this->isComposerProxy($path, $vendorDir);
    }

    private function isPhp(string $head): bool
    {
        if (str_starts_with($head, self::BOM)) {
            $head = substr($head, \strlen(self::BOM));
        }

        $line = 1 === \Safe\preg_match(self::SHEBANG, $head, $shebang) ? ($shebang[1] ?? null) : null;
        if (!\is_string($line)) {
            return 1 === \Safe\preg_match(self::OPEN_TAG, $head);
        }

        $words   = array_values(array_filter(explode(' ', strtr($line, "\t", ' ')), static fn (string $word): bool => '' !== $word));
        $command = array_shift($words);
        if (\is_string($command) && self::ENV === basename($command)) {
            $command = $this->envCommand(...$words);
        }

        return \is_string($command) && 1 === \Safe\preg_match(self::PHP_BINARY, basename($command));
    }

    /** The command env runs: its first word that is not an option, an option's argument or a NAME=value assignment. */
    private function envCommand(string ...$words): ?string
    {
        $isArgument = false;
        foreach ($words as $word) {
            if ($isArgument) {
                $isArgument = false;
            } elseif (\in_array($word, self::ENV_OPTIONS_WITH_ARGUMENT, true)) {
                $isArgument = true;
            } elseif (!str_starts_with($word, '-') && !str_contains($word, '=')) {
                return $word;
            }
        }

        return null;
    }

    /** Composer's proxy shape, start and end, including a path that resolves into the vendor dir. */
    private function isComposerProxy(string $path, ?string $vendorDir): bool
    {
        $contents = \Safe\file_get_contents($path, false, null, 0, self::PROXY_BYTES);
        if (null === $vendorDir
            || 1 !== \Safe\preg_match(self::COMPOSER_PROXY, $contents, $match)
            || 1 !== \Safe\preg_match(self::COMPOSER_PROXY_END, $contents)) {
            return false;
        }

        $included = $match[1] ?? null;
        if (!\is_string($included)) {
            return false;
        }

        if (!str_starts_with($included, '/')) {
            $included = \dirname(\Safe\realpath($path)) . '/' . $included;
        }

        return is_file($included) && $this->isInside(\Safe\realpath($included), $vendorDir);
    }
}
