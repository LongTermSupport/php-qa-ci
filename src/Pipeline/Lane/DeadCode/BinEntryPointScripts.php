<?php

declare(strict_types=1);

namespace LTS\PHPQA\Pipeline\Lane\DeadCode;

use FilesystemIterator;
use SplFileInfo;

/**
 * The PHP scripts directly under a project's bin/ that are not declared as dead-code entry
 * points.
 *
 * A bin/ script has no `.php` suffix, so the detector reads it only when it is listed with
 * withDeadCodeEntryPoints(). One left off the list is analysed by nothing, and every member
 * only it reaches is reported dead. A file is PHP by its content: a `#!` line naming a php
 * interpreter, or a `<?php` open tag at its start. Not required, each with the reason it holds
 * none of the project's own code:
 *
 * - a script in another language, which PHPStan does not read;
 * - a Composer binary proxy, which only includes a package's script;
 * - a symlink, whose code lives at its target (Composer links package binaries this way);
 * - anything in a subdirectory of bin/, which is a tool's own tree, not an executable.
 *
 * @internal
 */
final readonly class BinEntryPointScripts
{
    /** The directory scanned, relative to the project root, and the prefix of every path reported. */
    private const string BIN = 'bin';

    /** How many bytes of a file decide whether it is PHP: the shebang and the proxy header. */
    private const int HEAD_BYTES = 512;

    /** A file that starts with it is PHP whatever its name. */
    private const string OPEN_TAG = '<?php';

    /** The interpreter of a `#!` line is php, php8.5 and so on, directly or through env. */
    private const string PHP_SHEBANG = '~\A#!\s*(?:\S*/)?(?:env\s+(?:-\S+\s+)*)?(?:\S*/)?php[\d.]*(?=\s|\z)~';

    /** Composer writes this line into every PHP proxy it generates in its bin-dir. */
    private const string COMPOSER_PROXY = 'Proxy PHP file generated by Composer';

    /**
     * @param string $projectRoot absolute
     * @param string ...$declared absolute paths of the declared entry points
     *
     * @return list<string> project-relative paths (`bin/<name>`), sorted
     */
    public function undeclared(string $projectRoot, string ...$declared): array
    {
        $binDir = $projectRoot . '/' . self::BIN;
        if (!is_dir($binDir)) {
            return [];
        }

        $declaredFiles = [];
        foreach ($declared as $path) {
            if (is_file($path)) {
                $declaredFiles[\Safe\realpath($path)] = true;
            }
        }

        $undeclared = [];
        foreach (new FilesystemIterator($binDir, FilesystemIterator::SKIP_DOTS) as $file) {
            if (!$file instanceof SplFileInfo || $file->isLink() || !$file->isFile()) {
                continue;
            }

            $path = $file->getPathname();
            if (!isset($declaredFiles[\Safe\realpath($path)]) && $this->isFirstPartyPhp($path)) {
                $undeclared[] = self::BIN . '/' . $file->getFilename();
            }
        }

        sort($undeclared);

        return $undeclared;
    }

    private function isFirstPartyPhp(string $path): bool
    {
        $head = \Safe\file_get_contents($path, false, null, 0, self::HEAD_BYTES);
        if (!str_starts_with($head, self::OPEN_TAG) && 1 !== \Safe\preg_match(self::PHP_SHEBANG, $head)) {
            return false;
        }

        return !str_contains($head, self::COMPOSER_PROXY);
    }
}
